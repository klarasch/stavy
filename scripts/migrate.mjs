#!/usr/bin/env node
// Stavy migrate — moves a 0.2 workspace onto the 0.3 model without losing anything.
//
//   node scripts/migrate.mjs [stavy.json] [--write] [--states <pageId>]
//
//   (default)         dry run: prints what would change, writes nothing
//   --write           do it
//   --states <page>   also turn that page's pinned instances into named states
//                     (one state per instance, with the url it rendered at; scenario
//                     steps and notes that pointed at dims point at the state instead)
//
// 0.2 `boards[]` (mermaid / image / text) and `notes[]` become one generated board,
// stavy-content/boards/legacy.json, registered in stavy-content/index.json:
//   mermaid → mermaid item      image → image item (callouts kept)
//   text    → markdown item     note  → note item (page/dims/target kept as screen/dims/target)
// They are removed from stavy.json only with --write. Re-running is safe: items that are
// already in the board are not added twice.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { pathToFileURL } from "node:url"
import { CONTENT_DIR, resolveDims, statePath } from "./lib/model.mjs"

export const LEGACY_BOARD = "legacy"

const slug = (s) => String(s).replace(/[^A-Za-z0-9_.-]+/g, "-").replace(/^-+|-+$/g, "") || "state"
const strip = (o) => Object.fromEntries(Object.entries(o).filter(([, v]) => v !== undefined))

/** A legacy board → a board item. */
export function boardToItem(b) {
  const base = { id: b.id, title: b.title, ...(b.description ? { note: b.description } : {}), ...(b.width ? { w: b.width } : {}), ...(b.page ? { page: b.page } : {}) }
  if (b.kind === "mermaid") return strip({ ...base, type: "mermaid", code: b.source })
  if (b.kind === "image") return strip({ ...base, type: "image", src: b.source, alt: b.title, callouts: b.callouts })
  return strip({ ...base, type: "markdown", md: b.source })
}

/** A canvas note → a note item (what it pointed at stays as screen / dims / target). */
export function noteToItem(n) {
  return strip({ id: n.id, type: "note", text: n.text, screen: n.page, dims: n.dims, target: n.target, placement: n.placement, offset: n.offset })
}

/**
 * A page's pinned instances → named states. Returns the new states and a lookup
 * from a dims assignment (resolved) to the state id, used to rewrite references.
 */
export function pageToStates(page) {
  const insts = page.instances?.length ? page.instances : [{ dims: {} }]
  const used = new Set()
  const byDims = new Map()
  const states = insts.map((inst) => {
    const dims = resolveDims(page, inst.dims)
    const values = Object.values(dims)
    let id = slug(values.length ? values.join("-") : "default")
    for (let n = 2; used.has(id); n++) id = `${slug(values.join("-"))}-${n}`
    used.add(id)
    byDims.set(JSON.stringify(Object.entries(dims).sort()), id)
    return strip({ id, label: values.length ? values.join(" · ") : undefined, url: statePath(page, dims) ?? undefined, note: inst.note })
  })
  return { states, idFor: (d) => byDims.get(JSON.stringify(Object.entries(resolveDims(page, d)).sort())) }
}

/**
 * The whole conversion, on plain objects.
 * @returns { manifest, board, index, summary: string[], changed: boolean }
 */
export function migrate(manifest, { board: existingBoard, index: existingIndex, statesPage } = {}) {
  const m = structuredClone(manifest)
  const summary = []
  const board = existingBoard ? structuredClone(existingBoard) : { title: "Legacy boards and notes", description: "Generated by scripts/migrate.mjs from stavy.json (0.2).", items: [] }
  const have = new Set(board.items.map((i) => i.id))
  const fresh = (id) => {
    let out = id
    for (let n = 2; have.has(out); n++) out = `${id}-${n}`
    have.add(out)
    return out
  }

  const boardKinds = {}
  for (const b of m.boards ?? []) {
    if (board.items.some((i) => i.id === b.id && i.type === boardToItem(b).type)) continue // already migrated
    const item = boardToItem(b)
    item.id = fresh(item.id)
    board.items.push(item)
    boardKinds[item.type] = (boardKinds[item.type] ?? 0) + 1
    if (b.page) summary.push(`board "${b.id}" was a figure anchored to page "${b.page}": kept as the extra field page:"${b.page}" on its item`)
  }
  const nBoards = Object.values(boardKinds).reduce((a, b) => a + b, 0)
  if (nBoards) summary.push(`${nBoards} board(s) → ${Object.entries(boardKinds).map(([k, v]) => `${v} ${k}`).join(", ")} item(s) in ${CONTENT_DIR}/boards/${LEGACY_BOARD}.json`)

  let nNotes = 0
  for (const n of m.notes ?? []) {
    if (board.items.some((i) => i.id === n.id && i.type === "note")) continue
    const item = noteToItem(n)
    item.id = fresh(item.id)
    board.items.push(item)
    nNotes++
  }
  if (nNotes) summary.push(`${nNotes} note(s) → note item(s) in ${LEGACY_BOARD}.json (their page / dims / target kept as screen / dims / target)`)

  if (statesPage) {
    const page = (m.pages ?? []).find((p) => p.id === statesPage)
    if (!page) summary.push(`--states: no page "${statesPage}"`)
    else if (page.states) summary.push(`--states: page "${statesPage}" already has named states`)
    else {
      const { states, idFor } = pageToStates({ ...page, dimensions: page.dimensions ?? {} })
      for (const sc of m.scenarios ?? []) for (const st of sc.steps ?? []) if (st.page === page.id && (st.dims || !st.state)) {
        st.state = idFor(st.dims ?? {})
        delete st.dims
      }
      for (const it of board.items) if (it.type === "note" && it.screen === page.id) {
        it.state = idFor(it.dims ?? {})
        delete it.dims
      }
      page.states = states
      for (const k of ["url", "dimensions", "defaults", "instances"]) delete page[k]
      summary.push(`page "${statesPage}": ${states.length} instance(s) → named states (${states.map((s) => s.id).join(", ")}); url template, dimensions, defaults and instances removed from the page`)
    }
  }

  const index = existingIndex ? structuredClone(existingIndex) : {}
  index.boards ??= []
  index.docs ??= []
  const registered = board.items.length > 0 && !index.boards.some((b) => b.id === LEGACY_BOARD)
  if (registered) {
    index.boards.push({ id: LEGACY_BOARD, title: board.title, description: "Boards and notes carried over from stavy.json (0.2)" })
    summary.push(`registered "${LEGACY_BOARD}" in ${CONTENT_DIR}/index.json`)
  }
  const removing = [m.boards?.length ? "boards[]" : null, m.notes?.length ? "notes[]" : null].filter(Boolean)
  delete m.boards
  delete m.notes
  if (removing.length) summary.push(`removes ${removing.join(" and ")} from stavy.json`)
  return { manifest: m, board, index, summary, changed: summary.length > 0 }
}

function main() {
  const argv = process.argv.slice(2)
  const write = argv.includes("--write")
  const si = argv.indexOf("--states")
  const statesPage = si >= 0 ? argv[si + 1] : undefined
  const positional = argv.filter((a, i) => !a.startsWith("--") && argv[i - 1] !== "--states")
  const manifestPath = resolve(positional[0] ?? (existsSync("stavy.json") ? "stavy.json" : "public/stavy.json"))
  const root = dirname(manifestPath)
  const contentDir = join(root, CONTENT_DIR)
  const readJson = (p) => (existsSync(p) ? JSON.parse(readFileSync(p, "utf8")) : undefined)

  const manifest = readJson(manifestPath)
  const boardPath = join(contentDir, "boards", `${LEGACY_BOARD}.json`)
  const indexPath = join(contentDir, "index.json")
  const result = migrate(manifest, { board: readJson(boardPath), index: readJson(indexPath), statesPage })

  if (!result.changed) {
    console.log("migrate: nothing to do — no legacy boards or notes in " + manifestPath)
    return
  }
  console.log(`migrate${write ? "" : " (dry run)"}: ${manifestPath}`)
  for (const s of result.summary) console.log(`  ${write ? "✓" : "·"} ${s}`)
  if (!write) {
    console.log("\nNothing written. Re-run with --write to apply (commit first, so the change is reviewable).")
    return
  }
  mkdirSync(join(contentDir, "boards"), { recursive: true })
  if (result.board.items.length) writeFileSync(boardPath, JSON.stringify(result.board, null, 2) + "\n")
  writeFileSync(indexPath, JSON.stringify(result.index, null, 2) + "\n")
  writeFileSync(manifestPath, JSON.stringify(result.manifest, null, 2) + "\n")
  console.log("\nDone. Check the result with: npm run validate")
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main()
